public class OperadoresUnarios {
    public static void main(String[] args) {
        int numero = 5;

        numero = - numero; // Operador unário de negação

        //System.out.println(- numero); // Operador unário de negação

        System.out.println(numero); // Operador unário de positivo

        numero = + numero; // Operador unário de positivo
        System.out.println(numero);
    }
    
}
